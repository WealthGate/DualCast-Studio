module.exports = async function verifyOutputPerformance(fps = 30) {
  const { store, wait } = window.__transitionCheck;
  const { createStreamingCapture } = await import('/utils/streamingCapture.ts');
  const { onCanvasFrame } = await import('/utils/canvasFrames.ts');
  const { applyProjectionSignal, localProjectionDescription } = await import('/utils/projectionPeer.ts');
  const assert = (value, message) => { if (!value) throw Error(message); };
  const source = document.querySelector('.program-pane canvas');
  const previous = { send: window.dualcast.sendProjectionSignal, on: window.dualcast.onProjectionSignal, frame: window.dualcast.sendProgramFrame, Peer: window.RTCPeerConnection };
  const settings = store.getState().settings;
  const remote = new RTCPeerConnection({ iceServers: [] });
  const senders = [];
  window.RTCPeerConnection = class extends previous.Peer { constructor(options) { super(options); senders.push(this); } };
  let jpegFrames = 0;
  window.dualcast.sendProgramFrame = () => { jpegFrames++; };
  const sanctuary = document.createElement('video'); sanctuary.muted = true;
  let senderSignal = () => {};
  let signalingError = null;
  remote.onicecandidate = event => { if (event.candidate) senderSignal({ type: 'candidate', peerId: 1, candidate: event.candidate.toJSON() }); };
  remote.ontrack = event => { sanctuary.srcObject = event.streams[0]; void sanctuary.play(); };
  window.dualcast.onProjectionSignal = handler => { senderSignal = handler; return () => {}; };
  window.dualcast.sendProjectionSignal = signal => {
    if (signal.type === 'register') queueMicrotask(() => senderSignal({ type: 'ready', peerId: 1 }));
    if (signal.type === 'offer') void (async () => {
      await applyProjectionSignal(remote, signal);
      await remote.setLocalDescription(localProjectionDescription(await remote.createAnswer()));
      senderSignal({ type: 'answer', peerId: 1, description: remote.localDescription.toJSON() });
    })().catch(error => { signalingError = String(error); });
    if (signal.type === 'candidate') void applyProjectionSignal(remote, signal).catch(error => { signalingError = String(error); });
  };
  store.setState({ settings: { ...settings, sanctuaryDisplay: { ...settings.sanctuaryDisplay, mode: 'independent' }, networkOutput: { ...settings.networkOutput, enabled: false } } });
  await wait(100);
  store.setState({ isProjecting: true, settings: { ...settings, frameRate: fps, qualityPreset: 'medium', networkOutput: { ...settings.networkOutput, enabled: false }, sanctuaryDisplay: { ...settings.sanctuaryDisplay, mode: 'program' } } });
  for (let i = 0; i < 150 && (remote.connectionState !== 'connected' || sanctuary.readyState < 2); i++) await wait(30);
  assert(remote.connectionState === 'connected' && sanctuary.readyState >= 2, 'Sanctuary video failed to connect: ' + remote.connectionState + ' ' + signalingError);
  const capture = createStreamingCapture(source, 'low', fps);
  let captured = 0, displayed = 0, active = true, programFrames = 0;
  const processor = new MediaStreamTrackProcessor({ track: capture.stream.getVideoTracks()[0] });
  const reader = processor.readable.getReader();
  const readFrames = (async () => { while (active) { const result = await reader.read(); if (result.done) break; captured++; result.value.close(); } })();
  const countDisplay = () => { if (active) { displayed++; sanctuary.requestVideoFrameCallback(countDisplay); } };
  sanctuary.requestVideoFrameCallback(countDisplay);
  await wait(1500); captured = displayed = jpegFrames = 0;
  const unsubscribe = onCanvasFrame(source, () => { programFrames++; });
  const beforeStats = [...(await remote.getStats()).values()].find(report => report.type === 'inbound-rtp' && report.kind === 'video');
  const start = performance.now(); await wait(5000); const seconds = (performance.now() - start) / 1000;
  active = false;
  const stats = await remote.getStats();
  const inbound = [...stats.values()].find(report => report.type === 'inbound-rtp' && report.kind === 'video');
  const outbound = [...(await senders[0].getStats()).values()].find(report => report.type === 'outbound-rtp' && report.kind === 'video');
  const result = { requestedFps: fps, seconds: Number(seconds.toFixed(2)), programFps: Number((programFrames / seconds).toFixed(1)), sanctuaryFps: Number(((inbound.framesDecoded - (beforeStats?.framesDecoded ?? 0)) / seconds).toFixed(1)), presentedFps: Number((displayed / seconds).toFixed(1)), streamCaptureFps: Number((captured / seconds).toFixed(1)), rtcDecodedFrames: inbound?.framesDecoded, decoder: inbound?.decoderImplementation, jitterBufferMs: inbound?.jitterBufferEmittedCount ? Number((1000 * inbound.jitterBufferDelay / inbound.jitterBufferEmittedCount).toFixed(1)) : null, previewPixels: document.querySelector('.preview-pane canvas').width * document.querySelector('.preview-pane canvas').height, programPixels: source.width * source.height };
  Object.assign(result, {jpegFrames, sentWidth: outbound?.frameWidth, sentHeight: outbound?.frameHeight, encoder: outbound?.encoderImplementation, limitation: outbound?.qualityLimitationReason, senderFps: outbound?.framesPerSecond, codec: stats.get(inbound.codecId)?.mimeType});
  unsubscribe(); await reader.cancel(); await readFrames; capture.stop(); sanctuary.pause(); sanctuary.srcObject = null;
  senderSignal({ type: 'closed', peerId: 1 }); remote.close();
  window.dualcast.sendProjectionSignal = previous.send; window.dualcast.onProjectionSignal = previous.on;
  window.dualcast.sendProgramFrame = previous.frame; window.RTCPeerConnection = previous.Peer;
  store.setState({ isProjecting: false, settings });
  assert(result.programFps >= fps * 0.8 && result.sanctuaryFps >= result.programFps * 0.8, 'Sanctuary video did not keep pace with the rendered output: ' + JSON.stringify(result));
  assert(result.streamCaptureFps >= result.programFps * 0.85, 'Streaming capture did not follow completed Program frames: ' + JSON.stringify(result));
  assert(result.jpegFrames === 0 && result.jitterBufferMs < 150, 'Connected sanctuary video used the slow fallback or built a delay: ' + JSON.stringify(result));
  assert(result.previewPixels < result.programPixels / 2, 'Preview still renders full output resolution');
  return result;
};
